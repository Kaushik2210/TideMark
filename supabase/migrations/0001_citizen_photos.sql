-- Tidemark citizen photos: anyone may SUBMIT, nothing is shown until a moderator approves it.
--
-- Safety model (enforced here, not just in the website):
--   * the public (anon) role can INSERT a row that is forced to status = 'pending';
--   * the public can SELECT only rows with status = 'approved';
--   * the public can never UPDATE or DELETE, and cannot read the pending-upload bucket;
--   * approving a photo needs the service-role key (kept out of the browser), see docs/moderation.md.

create table if not exists public.photo_submissions (
  id             uuid primary key,                      -- generated by the browser so no read-back is needed
  lake_id        text not null check (lake_id ~ '^[a-z0-9_-]{2,40}$'),
  taken_on       date not null check (taken_on >= date '2016-01-01' and taken_on <= current_date),
  caption        text not null check (char_length(caption) between 3 and 280),
  consent        boolean not null check (consent),      -- submitter agrees to CC BY 4.0 publication
  pending_path   text not null check (pending_path ~ '^pending/[0-9a-f-]{36}\.(jpg|png|webp)$'),
  status         text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  public_path    text,                                  -- set by the moderator when approved
  moderator_note text,
  created_at     timestamptz not null default now(),
  reviewed_at    timestamptz,
  constraint approved_has_public_path check (status <> 'approved' or public_path is not null)
);

alter table public.photo_submissions enable row level security;

drop policy if exists "anyone can submit a pending photo" on public.photo_submissions;
create policy "anyone can submit a pending photo" on public.photo_submissions
  for insert to anon
  with check (status = 'pending' and public_path is null and moderator_note is null
              and reviewed_at is null and consent);

drop policy if exists "anyone can read approved photos" on public.photo_submissions;
create policy "anyone can read approved photos" on public.photo_submissions
  for select to anon
  using (status = 'approved');

-- Public columns only: the approved-photo list never exposes the moderator's private note.
revoke all on public.photo_submissions from anon;
grant insert (id, lake_id, taken_on, caption, consent, pending_path) on public.photo_submissions to anon;
grant select (id, lake_id, taken_on, caption, public_path, created_at) on public.photo_submissions to anon;

-- Storage: a private bucket for uploads waiting for review, a public bucket for approved photos.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('submissions', 'submissions', false, 5242880, array['image/jpeg', 'image/png', 'image/webp'])
on conflict (id) do update set public = false, file_size_limit = 5242880,
  allowed_mime_types = array['image/jpeg', 'image/png', 'image/webp'];

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('public-photos', 'public-photos', true, 5242880, array['image/jpeg', 'image/png', 'image/webp'])
on conflict (id) do update set public = true;

drop policy if exists "anyone can upload to pending" on storage.objects;
create policy "anyone can upload to pending" on storage.objects
  for insert to anon
  with check (bucket_id = 'submissions' and name ~ '^pending/[0-9a-f-]{36}\.(jpg|png|webp)$');
-- No select/update/delete policy on 'submissions' for anon: uploads cannot be read back or replaced.
